// The gesture tables of the Ars Goetia invocation plates (Claude Design, "Invocation Plates" handoff,
// archived in docs/frontend/): one painted concept per invocation, not a figure (Aurevora is a maw of
// gold, Astiwihad a noose), in the design's own notation so the table diffs cleanly against a future
// handoff. Tune a plate here, then re-bake (`pnpm --filter @panvitium/web bake:plates`); the brush
// lives in brush.ts and the plate layers in invocationPlates.ts.
//
// ORDER IS LOAD-BEARING. A plate's position seeds every one of its strokes (and picks its stone), so
// reordering the table repaints the plates. It follows the sim catalog's order; append new plates at
// the end, never insert or reorder.
import type { Dab, Gesture, Point } from './brush.js';

/** The plate's design box: a 3:4 portrait, 300 × 400 units. */
export const PLATE_WIDTH = 300;
export const PLATE_HEIGHT = 400;

/** One invocation's plate: its gestures and dabs, painted in order. */
export interface InvocationPlateDef {
  /** The invocation id (the `INVOCATIONS` key in packages/sim). */
  readonly id: string;
  readonly marks: readonly (Gesture | Dab)[];
}

/** A gesture: its centreline, its width, and any of the brush options. */
const g = (p: readonly Point[], w: number, o: Omit<Gesture, 'p' | 'w'> = {}): Gesture => ({
  p,
  w,
  ...o,
});
/** A solid dab; round unless given a second radius. */
const D = (x: number, y: number, rx: number, ry?: number): Dab => ({ dot: [x, y, rx, ry ?? rx] });
/** A centreline reflected across the plate's vertical axis, for symmetric pairs. */
const mirror = (pts: readonly Point[]): Point[] => pts.map(([x, y]): Point => [PLATE_WIDTH - x, y]);

